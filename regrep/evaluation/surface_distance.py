@functools.lru_cache(maxsize=16)
def _surface_area_table(spacing_mm: tuple[float, float, float]) -> np.ndarray:
    """Return the surface area in mm^2 for each of the 256 neighbourhood codes."""
    table = np.zeros([256])
    for code in range(256):
        normals = np.array(_NEIGHBOUR_CODE_TO_NORMALS[code])
        sum_area = 0
        for normal_idx in range(normals.shape[0]):
            n = np.zeros([3])
            n[0] = normals[normal_idx, 0] * spacing_mm[1] * spacing_mm[2]
            n[1] = normals[normal_idx, 1] * spacing_mm[0] * spacing_mm[2]
            n[2] = normals[normal_idx, 2] * spacing_mm[0] * spacing_mm[1]
            sum_area += np.linalg.norm(n)
        table[code] = sum_area
    table.setflags(write=False)
    return table


def _bounding_box(mask: np.ndarray):
    """Return the first and last corner of the bounding box of ``mask``.

    Both are ``None`` when the mask is empty.
    """
    num_dims = mask.ndim
    bbox_min = np.zeros(num_dims, np.int64)
    bbox_max = np.zeros(num_dims, np.int64)
    for axis in range(num_dims):
        other_axes = tuple(a for a in range(num_dims) if a != axis)
        idx_nonzero = np.nonzero(np.amax(mask, axis=other_axes))[0]
        if len(idx_nonzero) == 0:
            return None, None
        bbox_min[axis] = np.min(idx_nonzero)
        bbox_max[axis] = np.max(idx_nonzero)
    return bbox_min, bbox_max


def _crop_to_bounding_box(mask, bbox_min, bbox_max):
    """Crop ``mask`` to the box and add one zero voxel at the high side of each axis.

    The extra voxel gives the full result of the 2x2x2 correlation.
    """
    cropmask = np.zeros((bbox_max - bbox_min) + 2, np.uint8)
    cropmask[0:-1, 0:-1, 0:-1] = mask[
        bbox_min[0] : bbox_max[0] + 1,
        bbox_min[1] : bbox_max[1] + 1,
        bbox_min[2] : bbox_max[2] + 1,
    ]
    return cropmask


def _sort_distances_surfels(distances, surfel_areas):
    """Sort the distances and their surfel areas by (distance, area)."""
    order = np.lexsort((surfel_areas, distances))
    return distances[order], surfel_areas[order]


def compute_surface_distances(mask_gt, mask_pred, spacing_mm):
    """Compute the distance from every surface element to the other surface.

    Parameters
    ----------
    mask_gt, mask_pred : numpy.ndarray
        3-D boolean masks of the same shape.
    spacing_mm : sequence of float
        Voxel size along the three array axes.

    Returns
    -------
    dict
        ``distances_gt_to_pred`` and ``distances_pred_to_gt`` (mm, sorted in
        increasing order) and the matching ``surfel_areas_gt`` and
        ``surfel_areas_pred`` (mm^2). When one mask is empty, its lists are
        empty and every distance from the other mask is ``inf``.
    """
    for name, mask in (("mask_gt", mask_gt), ("mask_pred", mask_pred)):
        if not isinstance(mask, np.ndarray) or mask.dtype != bool:
            raise ValueError(f"{name} must be a boolean numpy array")
        if mask.ndim != 3:
            raise ValueError(f"{name} must be 3-D, not of shape {mask.shape}")
    if len(spacing_mm) != 3:
        raise ValueError("spacing_mm must have three elements")

    spacing_mm = tuple(float(s) for s in spacing_mm)
    neighbour_code_to_surface_area = _surface_area_table(spacing_mm)
    kernel = ENCODE_NEIGHBOURHOOD_3D_KERNEL
    full_true_neighbours = 0b11111111

    bbox_min, bbox_max = _bounding_box(mask_gt | mask_pred)
    if bbox_min is None:
        return {
            "distances_gt_to_pred": np.array([]),
            "distances_pred_to_gt": np.array([]),
            "surfel_areas_gt": np.array([]),
            "surfel_areas_pred": np.array([]),
        }

    cropmask_gt = _crop_to_bounding_box(mask_gt, bbox_min, bbox_max)
    cropmask_pred = _crop_to_bounding_box(mask_pred, bbox_min, bbox_max)

    # The neighbour code of each voxel corner. The code maps are shifted by
    # half a voxel towards the origin on each axis.
    neighbour_code_map_gt = ndimage.correlate(
        cropmask_gt.astype(np.uint8), kernel, mode="constant", cval=0
    )
    neighbour_code_map_pred = ndimage.correlate(
        cropmask_pred.astype(np.uint8), kernel, mode="constant", cval=0
    )

    borders_gt = (neighbour_code_map_gt != 0) & (
        neighbour_code_map_gt != full_true_neighbours
    )
    borders_pred = (neighbour_code_map_pred != 0) & (
        neighbour_code_map_pred != full_true_neighbours
    )

    if borders_gt.any():
        distmap_gt = ndimage.distance_transform_edt(~borders_gt, sampling=spacing_mm)
    else:
        distmap_gt = np.inf * np.ones(borders_gt.shape)
    if borders_pred.any():
        distmap_pred = ndimage.distance_transform_edt(
            ~borders_pred, sampling=spacing_mm
        )
    else:
        distmap_pred = np.inf * np.ones(borders_pred.shape)

    surface_area_map_gt = neighbour_code_to_surface_area[neighbour_code_map_gt]
    surface_area_map_pred = neighbour_code_to_surface_area[neighbour_code_map_pred]

    distances_gt_to_pred = distmap_pred[borders_gt]
    distances_pred_to_gt = distmap_gt[borders_pred]
    surfel_areas_gt = surface_area_map_gt[borders_gt]
    surfel_areas_pred = surface_area_map_pred[borders_pred]

    if distances_gt_to_pred.shape != (0,):
        distances_gt_to_pred, surfel_areas_gt = _sort_distances_surfels(
            distances_gt_to_pred, surfel_areas_gt
        )
    if distances_pred_to_gt.shape != (0,):
        distances_pred_to_gt, surfel_areas_pred = _sort_distances_surfels(
            distances_pred_to_gt, surfel_areas_pred
        )

    return {
        "distances_gt_to_pred": distances_gt_to_pred,
        "distances_pred_to_gt": distances_pred_to_gt,
        "surfel_areas_gt": surfel_areas_gt,
        "surfel_areas_pred": surfel_areas_pred,
    }


def compute_robust_hausdorff(surface_distances, percent):
    """Return the robust Hausdorff distance in mm.

    For each direction, the distance is the ``percent`` percentile of the
    surface distances, with each surface element weighted by its area. The
    result is the larger of the two directions. A direction with no surface
    elements gives ``inf``.
    """
    distances_gt_to_pred = surface_distances["distances_gt_to_pred"]
    distances_pred_to_gt = surface_distances["distances_pred_to_gt"]
    surfel_areas_gt = surface_distances["surfel_areas_gt"]
    surfel_areas_pred = surface_distances["surfel_areas_pred"]
    if len(distances_gt_to_pred) > 0:
        surfel_areas_cum_gt = np.cumsum(surfel_areas_gt) / np.sum(surfel_areas_gt)
        idx = np.searchsorted(surfel_areas_cum_gt, percent / 100.0)
        perc_distance_gt_to_pred = distances_gt_to_pred[
            min(idx, len(distances_gt_to_pred) - 1)
        ]
    else:
        perc_distance_gt_to_pred = np.inf

    if len(distances_pred_to_gt) > 0:
        surfel_areas_cum_pred = np.cumsum(surfel_areas_pred) / np.sum(
            surfel_areas_pred
        )
        idx = np.searchsorted(surfel_areas_cum_pred, percent / 100.0)
        perc_distance_pred_to_gt = distances_pred_to_gt[
            min(idx, len(distances_pred_to_gt) - 1)
        ]
    else:
        perc_distance_pred_to_gt = np.inf

    return max(perc_distance_gt_to_pred, perc_distance_pred_to_gt)


def compute_dice_coefficient(mask_gt, mask_pred):
    """Return the Dice coefficient of two boolean masks, or NaN if both are empty."""
    volume_sum = mask_gt.sum() + mask_pred.sum()
    if volume_sum == 0:
        return np.nan
    volume_intersect = (mask_gt & mask_pred).sum()
    return 2 * volume_intersect / volume_sum
